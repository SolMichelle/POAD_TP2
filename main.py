import matplotlib.pyplot as plt
import ipywidgets as widgets
from ipywidgets import interact

# 1. Definir las métricas disponibles para el selector
opciones_metricas = {
    'Riesgo de automatización (%)': 'Market_Automation_Risk_Pct',
    'Salario mediano (USD)': 'Market_Median_Salary_USD',
    'Porcentaje de trabajo remoto (%)': 'Market_Remote_Work_Ratio_Pct',
    'Años de experiencia requerida': 'Market_Experience_Required_Yrs'
}

# 2. Función del gráfico en Matplotlib
def graficar_top_puestos(metrica_etiqueta):
    columna_metrica = opciones_metricas[metrica_etiqueta]

    # Agrupar por puesto para calcular el promedio de la métrica seleccionada
    top_10 = (
        df_final_pd.groupby('Job_Title', as_index=False)[columna_metrica]
        .mean()
        .nlargest(10, columna_metrica)
    )

    # Crear figura y ejes
    fig, ax = plt.subplots(figsize=(9, 5))

    # Dibujar barras horizontales
    barras = ax.barh(
        top_10['Job_Title'],
        top_10[columna_metrica],
        color='#34495e',
        edgecolor='black',
        alpha=0.85
    )

    # Personalización sencilla
    ax.set_xlabel(metrica_etiqueta, fontsize=11, fontweight='bold')
    ax.set_title(f'Top 10 roles con mayor: {metrica_etiqueta}', fontsize=12, fontweight='bold', pad=12)
    ax.grid(axis='x', linestyle='--', alpha=0.5)
    ax.invert_yaxis()  # Invertir eje Y para ver el primer puesto arriba

    # Etiquetar los valores en las barras
    for barra in barras:
        ancho = barra.get_width()
        formato = f'${ancho:,.0f}' if 'USD' in metrica_etiqueta else f'{ancho:.1f}'
        ax.text(
            ancho * 1.01,
            barra.get_y() + barra.get_height()/2,
            formato,
            va='center',
            fontsize=9
        )

    plt.tight_layout()
    plt.show()

# 3. Widget interactivo
interact(
    graficar_top_puestos,
    metrica_etiqueta=widgets.Dropdown(
        options=list(opciones_metricas.keys()),
        value='Riesgo de automatización (%)',
        description='Métrica:',
        style={'description_width': 'initial'}
    )
);

