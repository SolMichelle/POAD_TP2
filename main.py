from pyspark.sql import functions as F

# 1. TRANSFORMACIÓN Y HOMOLOGACIÓN DE DF_1 (JOB MARKET)
df_1_transformed = df_copia_1 \
    .withColumn("Industry", F.trim(F.col("Industry"))) \
    .withColumn("Job_Title", F.trim(F.col("Job Title"))) \
    .withColumn("Market_Required_Education",
        F.when(F.col("Required Education").contains("Master"), "Master")
         .when(F.col("Required Education").contains("Bachelor"), "Bachelor")
         .when(F.col("Required Education").contains("PhD"), "PhD")
         .when(F.col("Required Education").contains("High School"), "High School")
         .otherwise(F.trim(F.col("Required Education")))
    ) \
    .withColumn("Market_Automation_Risk_Cat",
        F.when(F.col("Automation Risk (%)") < 33.0, "Low")
         .when(F.col("Automation Risk (%)") < 66.0, "Moderate")
         .otherwise("High")
    ) \
    .select(
        F.col("Industry"),
        F.col("Job_Title"),
        F.col("Job Status").alias("Market_Job_Status"),
        F.col("AI Impact Level").alias("Market_AI_Impact_Level"),
        F.col("Median Salary (USD)").cast("double").alias("Market_Median_Salary_USD"),
        F.col("Market_Required_Education"),
        F.col("Experience Required (Years)").cast("double").alias("Market_Experience_Required_Yrs"),
        F.col("Job Openings (2024)").cast("integer").alias("Market_Job_Openings_2024"),
        F.col("Projected Openings (2030)").cast("integer").alias("Market_Projected_Openings_2030"),
        F.col("Remote Work Ratio (%)").cast("double").alias("Market_Remote_Work_Ratio_Pct"),
        F.col("Automation Risk (%)").cast("double").alias("Market_Automation_Risk_Pct"),
        F.col("Market_Automation_Risk_Cat"),
        F.col("Location")
    )

# 2. TRANSFORMACIÓN Y AGRUPACIÓN DE DF_2 (EMPLOYEES SAMPLE)

# A. Limpieza de cadenas e indicador de trabajo remoto
df_2_transformed = df_copia_2 \
    .withColumn("Industry", F.trim(F.col("Industry"))) \
    .withColumn("Job_Role", F.trim(F.col("Job_Role"))) \
    .withColumn("is_remote", F.when(F.trim(F.col("Remote_Work")) == "Yes", 1.0).otherwise(0.0))

# B. Agregación a nivel de Industria y Rol
df_2_agg = df_2_transformed.groupBy("Industry", "Job_Role").agg(
    F.count("Employee_ID").alias("Emp_Sample_Size"),
    F.percentile_approx("Salary_Before_AI", 0.5).alias("Emp_Median_Salary_Before"),
    F.percentile_approx("Salary_After_AI", 0.5).alias("Emp_Median_Salary_After"),
    (F.avg("is_remote") * 100.0).alias("Emp_Remote_Work_Ratio_Pct"),
    F.avg("Job_Satisfaction").alias("Emp_Avg_Satisfaction"),
    F.avg("Productivity_Change_%").alias("Emp_Avg_Productivity_Change_Pct"),
    F.avg("Work_Hours_Per_Week").alias("Emp_Avg_Work_Hours")
)

# 3. CONSOLIDACIÓN (LEFT JOIN)

# Unión sobre las claves compuestas: Industry y Job_Title / Job_Role
df_consolidated = df_1_transformed.join(
    df_2_agg,
    (df_1_transformed["Industry"] == df_2_agg["Industry"]) &
    (df_1_transformed["Job_Title"] == df_2_agg["Job_Role"]),
    how="left"
) \
.drop(df_2_agg["Industry"]) \
.drop(df_2_agg["Job_Role"])

# Rellenar valores nulos de las agregaciones si una combinación del mercado no tuvo encuestados
df_consolidated = df_consolidated.fillna({"Emp_Sample_Size": 0})

df_2_agg.printSchema()
df_2_agg.show(5)

df_1_transformed.printSchema()
df_1_transformed.show(5)

"""Se integraron dos orígenes de datos mediante un pipeline de ETL en PySpark. Para garantizar la consistencia analítica y evitar duplicación de observaciones por disparidad de granularidad (30.000 registros de puestos globales vs. 2.000 registros de empleados individuales), el dataset de empleados (DF2) fue sometido a una agregación previa (groupBy) a nivel de Industry y Job_Role.

Transformaciones y homologaciones clave:

1. Trabajo remoto: la variable categórica Remote_Work (Yes/No) del DF2 se transformó en una métrica porcentual continua (Emp_Remote_Work_Ratio_Pct) para permitir la comparación directa con la variable Remote Work Ratio (%) del DF1.
2. Riesgo de automatización: se derivó la columna categórica Market_Automation_Risk_Cat en el DF1 a partir de sus valores porcentuales para hacerla homologable con las escalas cualitativas del DF2.
3. Se estandarizó la columna de educación requerida en DF1 para simplificar valores extensos (de "Master’s Degree" a "Master").
4. Tipos de datos y Nulos: se castearon las métricas cuantitativas a tipos numéricos (double/integer) y se asignó un valor por defecto ($0$) al tamaño de muestra (Emp_Sample_Size) para combinaciones sin encuestados.
5. Unión: se ejecutó un LEFT JOIN conservando el 100% de la representatividad del mercado global (DF1) utilizando la clave compuesta [Industry, Job_Title] <--> [Industry, Job_Role].
"""

